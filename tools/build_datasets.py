def korean_acquisitions():
    """Keep product identifiers and public previews when two products share a pass."""
    source = json.loads((ROOT / "data/korea-archive.json").read_text(encoding="utf-8"))
    acquisitions = defaultdict(list)
    for product in source["products"]:
        acquisition = product["scene_id"].rsplit("_", 1)[0]
        acquisitions[acquisition].append(product)

    for acquisition, products in acquisitions.items():
        first = products[0]
        levels = sorted({product["level"] for product in products})
        day = first["acquisition_start"][:10].replace("-", "")
        details = "L1A retains phase." if "L1A" in levels else "L1B contains intensity only."
        if len(levels) == 2:
            details = "L1A retains phase. L1B is an intensity product from the same acquisition."
        yield {
            "id": f"kompsat5-{day}",
            "group": "k",
            "title": "KOMPSAT-5 Giza archive pass",
            "date": first["acquisition_start"],
            "date_kind": "Acquisition start UTC",
            "end_utc": first["acquisition_end"],
            "platform": "KOMPSAT-5",
            "product": f'{first["mode"]}, {", ".join(levels)}',
            "site": "Giza plateau, Egypt",
            "access": "Public archive listing; commercial order",
            "url": "https://spaceeye.si-imaging.com/",
            "description": f"{details} The catalogue footprint covers the three pyramids. No full scene was used in the chamber tests.",
            "rights_key": "KOMPSAT",
            "source_ids": [p["scene_id"] for p in products],
            "catalog_retrieved": source["retrieved"],
        }


def build():
    output = []
    for record in [*RECORDS, *korean_acquisitions()]:
        item = dict(record)
        item["group"] = GROUPS[item["group"]]
        item["rights"], rights_url = RIGHTS[item.pop("rights_key")]
        if rights_url:
            item["rights_url"] = rights_url
        if item.get("url") is None:
            item.pop("url", None)
        output.append(item)
    ids = {item["id"] for item in output}
    if len(ids) != len(output):
        raise ValueError("Multiple records share an ID")
    for item in output:
        for linked in item.get("related", []):
            if linked not in ids:
                raise ValueError(f"Unknown related ID {linked}")
        urls = [a["url"] for a in item.get("assets", [])]
        urls.extend(item[k] for k in ("url", "rights_url") if k in item)
        if any(urlsplit(url).scheme != "https" or not urlsplit(url).hostname for url in urls):
            raise ValueError(f"Expected an HTTPS source for {item['id']}")
    return {
        "as_of": "2026-11-27",
        "scope": "Giza radar scenes, historical acquisition records, ground surveys and external controls used in the evidence review. Each record labels the meaning of its date. One pass can have several products. Archive counts reflect the dated searches.",
        "items": output,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the shipped catalogue without writing.")
    args = parser.parse_args()
    serialized = json.dumps(build(), ensure_ascii=False, indent=2) + "\n"
    target = ROOT / "data/datasets.json"
    if args.check:
        if serialized != target.read_text(encoding="utf-8"):
            raise SystemExit("Rebuild the catalogue with tools/build_datasets.py")
    else:
        target.write_text(serialized, encoding="utf-8")
    print(f"{len(json.loads(serialized)['items'])} dataset records")


if __name__ == "__main__":
    main()
